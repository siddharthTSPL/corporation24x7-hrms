const ExcelJS = require("exceljs");
const { toExcelDate } = require("./dates");

const NUM_FMT = {
  currency: "#,##0.00",
  number: "#,##0.00",
  hours: "0.00",
  percent: '0.00"%"',
  integer: "#,##0",
  date: "dd-mmm-yyyy",
  datetime: "dd-mmm-yyyy hh:mm",
  time: "hh:mm",
};
const DATE_TYPES = new Set(["date", "datetime", "time"]);
const NUM_TYPES = new Set(["currency", "number", "hours", "percent", "integer"]);

/**
 * CSV/Excel formula-injection guard: a text cell that begins with = + - @
 * (or a tab / CR) would be executed as a formula when opened. Prefix a single
 * quote so it is always treated as text. Same convention as the existing
 * client-side timesheetReportExport.js.
 */
function sanitizeText(v) {
  const s = String(v);
  return /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
}

function cellValue(col, v) {
  if (v === null || v === undefined || v === "") return null;
  if (DATE_TYPES.has(col.type)) {
    const d = new Date(v);
    return Number.isNaN(d.getTime()) ? null : toExcelDate(d);
  }
  if (NUM_TYPES.has(col.type)) {
    const n = Number(v);
    return Number.isFinite(n) ? n : null;
  }
  return sanitizeText(v);
}

/**
 * Streams a workbook to `res` row by row (constant memory, handles 100k+ rows).
 *   meta: { reportName, organisationName, period, filterLines[], generatedAt (Date),
 *           generatedBy, notes[] }
 *   rows: async iterable of row objects keyed by column key
 *   accumulator: from summary.makeAccumulator
 * Returns the number of data rows written.
 */
async function streamWorkbook({ res, columns, meta, rows, accumulator, maxRows, isAborted = () => false }) {
  const wb = new ExcelJS.stream.xlsx.WorkbookWriter({ stream: res, useStyles: true, useSharedStrings: false });
  wb.creator = "TorchX Talent";
  wb.created = new Date(meta.generatedAt);

  const info = [
    [meta.reportName],
    [`Organisation: ${meta.organisationName || "-"}`],
    [`Reporting period: ${meta.period || "-"}`],
    [`Filters applied: ${meta.filterLines.length ? meta.filterLines.join(" | ") : "None"}`],
    [`Generated at: ${meta.generatedAtText}`],
    [`Generated by: ${meta.generatedBy || "-"}`],
    ...(meta.notes || []).map((n) => [`Note: ${n}`]),
    [],
  ];
  const headerRowNo = info.length + 1;
  const ws = wb.addWorksheet(meta.reportName.slice(0, 31).replace(/[\\/?*[\]:]/g, " "), {
    views: [{ state: "frozen", ySplit: headerRowNo }],
  });
  columns.forEach((c, i) => { ws.getColumn(i + 1).width = c.width || 16; });

  info.forEach((vals, idx) => {
    const r = ws.addRow(vals.map(sanitizeText));
    if (idx === 0) r.font = { bold: true, size: 14, color: { argb: "FF730042" } };
    r.commit();
  });

  const head = ws.addRow(columns.map((c) => c.header));
  head.font = { bold: true, color: { argb: "FFFFFFFF" } };
  head.eachCell((cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF730042" } };
    cell.alignment = { vertical: "middle", horizontal: "center", wrapText: true };
  });
  head.commit();
  ws.autoFilter = { from: { row: headerRowNo, column: 1 }, to: { row: headerRowNo, column: columns.length } };

  let written = 0;
  for await (const row of rows) {
    if (isAborted()) break;
    if (written >= maxRows) {
      const err = new Error(`Export exceeds the ${maxRows.toLocaleString("en-IN")} row limit. Narrow the filters and export again.`);
      err.statusCode = 422;
      throw err;
    }
    accumulator.add(row);
    const r = ws.addRow(columns.map((c) => cellValue(c, row[c.key])));
    columns.forEach((c, i) => {
      const fmt = NUM_FMT[c.type];
      if (fmt) r.getCell(i + 1).numFmt = fmt;
    });
    r.commit();
    written += 1;
  }

  if (!written) {
    const r = ws.addRow(["No records match the selected filters."]);
    r.font = { italic: true };
    r.commit();
  }

  const { columnTotals, items } = accumulator.result();
  if (written && Object.keys(columnTotals).length) {
    const t = ws.addRow(columns.map((c, i) => (i === 0 ? "Total" : columnTotals[c.key] ?? null)));
    t.font = { bold: true };
    columns.forEach((c, i) => { const fmt = NUM_FMT[c.type]; if (fmt && columnTotals[c.key] !== undefined) t.getCell(i + 1).numFmt = fmt; });
    t.commit();
  }
  if (written && items.length) {
    ws.addRow([]).commit();
    const h = ws.addRow(["Summary"]);
    h.font = { bold: true };
    h.commit();
    for (const it of items) {
      const r = ws.addRow([it.label, it.value]);
      const fmt = NUM_FMT[it.type];
      if (fmt) r.getCell(2).numFmt = fmt;
      r.commit();
    }
  }

  ws.commit();
  await wb.commit();
  return written;
}

module.exports = { streamWorkbook, sanitizeText, cellValue, NUM_FMT };
