const { fmtPeriod } = require("../engine/dates");
const { makeAccumulator } = require("../engine/summary");
const { resolveNames } = require("../engine/people");
const { round2 } = require("./_shared");
const { ALL_STATUSES, STATUS_LABEL, PERIOD_FILTERS, periodOf, payrollDocsByMonth } = require("./_payroll");

const STATUS_OPTIONS = ALL_STATUSES.map((s) => ({ value: s, label: STATUS_LABEL[s] }));
const columns = [
  { key: "uid", header: "Employee ID", type: "text", width: 14 },
  { key: "name", header: "Employee Name", type: "text", width: 26 },
  { key: "department", header: "Department", type: "text", width: 18 },
  { key: "period", header: "Payroll Period", type: "text", width: 14 },
  { key: "netSalary", header: "Net Salary", type: "currency", width: 15, total: true },
  { key: "status", header: "Processing Status", type: "text", width: 18 },
  { key: "generatedOn", header: "Generated On", type: "date", width: 14 },
  { key: "generatedBy", header: "Generated By", type: "text", width: 22 },
  { key: "approvedBy", header: "Approved By", type: "text", width: 22 },
  { key: "paidOn", header: "Paid On", type: "date", width: 14 },
];

module.exports = {
  key: "payroll-processing-status",
  name: "Payroll Processing & Payment Status",
  category: "payroll",
  sensitive: true,
  description: "Where every payslip stands: generated, approved, paid or on hold, with who and when.",
  filters: [
    ...PERIOD_FILTERS.filter((f) => f.key !== "includeNonFinal"),
    { key: "statuses", label: "Status", type: "multiselect", options: STATUS_OPTIONS },
  ],
  columns,
  notes: [
    "Unlike the Payroll Register this report shows ALL statuses by design; the summary lists the net amount per status.",
    "Approval time is not stored as its own field, so only 'Approved By' (not an approval date) is available. Payment date is shown for paid payslips.",
    "Bank and account details are intentionally excluded.",
  ],
  period: (f) => {
    const { from, to } = periodOf(f);
    return from.year === to.year && from.month === to.month ? fmtPeriod(from.year, from.month) : `${fmtPeriod(from.year, from.month)} to ${fmtPeriod(to.year, to.month)}`;
  },
  validate(f) { periodOf(f); },
  accumulator() {
    const base = makeAccumulator(columns);
    const by = {};
    return {
      add(row) { base.add(row); const b = (by[row.status] ||= { n: 0, net: 0 }); b.n += 1; b.net = round2(b.net + row.netSalary); },
      result() {
        const r = base.result();
        r.columnTotals = {};
        r.items = [r.items[0], ...Object.entries(by).flatMap(([k, v]) => [
          { label: `${k} - payslips`, value: v.n, type: "integer" },
          { label: `${k} - net amount`, value: v.net, type: "currency" },
        ])];
        return r;
      },
    };
  },
  async *rows(ctx, f) {
    const statuses = f.statuses?.length ? f.statuses : ALL_STATUSES;
    for await (const docs of payrollDocsByMonth(ctx, f, { statuses, extraSelect: "generatedBy generatedByModel approvedBy approvedByModel paidOn createdAt" })) {
      const names = await resolveNames(ctx, docs.flatMap((d) => [
        { id: d.generatedBy, model: d.generatedByModel }, { id: d.approvedBy, model: d.approvedByModel },
      ]));
      yield docs.map((d) => ({
        uid: d.employeeSnapshot?.employeeId || "", name: d.employeeSnapshot?.name || "", department: d.employeeSnapshot?.department || "",
        period: fmtPeriod(d.year, d.month), netSalary: round2(d.netSalary), status: STATUS_LABEL[d.status] || d.status,
        generatedOn: d.createdAt || null,
        generatedBy: (d.generatedBy && names.get(`${d.generatedByModel}:${d.generatedBy}`)) || "",
        approvedBy: (d.approvedBy && names.get(`${d.approvedByModel}:${d.approvedBy}`)) || "",
        paidOn: d.paidOn || null,
      }));
    }
  },
};
