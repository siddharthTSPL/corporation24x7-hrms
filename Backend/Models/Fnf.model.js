const mongoose = require("mongoose");

// Rounds to 2 decimals and turns -0 / NaN into a plain 0,
// so the DB never stores -0 or tiny float remainders like -0.0000001.
const money = (v) => Math.round((Number(v) || 0) * 100) / 100 || 0;

const fnfSchema = new mongoose.Schema(
  {
    organisation_id: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "SuperAdmin",
      required: true,
      index: true,
    },

    employee: {
      type: mongoose.Schema.Types.ObjectId,
      refPath: "employeeModel",
      required: true,
    },
    employeeModel: {
      type: String,
      required: true,
      enum: ["User", "Manager", "Admin", "SuperAdmin"],
    },

    exitType: { type: String, enum: ["resigned", "fired", "terminated"], required: true },

    dateOfJoining: { type: Date, default: null },
    dateOfResignation: { type: Date, default: null }, // date the exit was initiated / notice given
    dateOfLeaving: { type: Date, default: null }, // last working day
    settlementMonth: { type: Number, default: null, min: 1, max: 12 },
    settlementYear: { type: Number, default: null },
    totalDaysInMonth: { type: Number, default: 0 },
    payableDaysInMonth: { type: Number, default: 0 },

    employeeSnapshot: {
      name: { type: String, default: "" },
      employeeId: { type: String, default: "" }, // uid/empid
      department: { type: String, default: "" },
      designation: { type: String, default: "" },
      pan: { type: String, default: "" },
      bankAccountNumber: { type: String, default: "" },
      bankName: { type: String, default: "" },
    },

    organisationSnapshot: {
      name: { type: String, default: "" },
    },

    ctc: { type: Number, default: 0 },

    income: {
      basic: { type: Number, default: 0, set: money },
      hra: { type: Number, default: 0, set: money },
      allowances: [{ name: String, amount: { type: Number, set: money }, _id: false }],
      total: { type: Number, default: 0, set: money },
    },

    otherIncome: {
      items: [{ particular: String, amount: { type: Number, set: money }, _id: false }], // e.g. leave encashment
      total: { type: Number, default: 0, set: money },
    },

    holding: {
      salaryOnHold: { type: Number, default: 0, set: money },
      reimbursementOnHold: { type: Number, default: 0, set: money },
      assetRecovery: { type: Number, default: 0, set: money },
      total: { type: Number, default: 0, set: money },
    },

    deductions: {
      pf: { type: Number, default: 0, set: money },
      professionalTax: { type: Number, default: 0, set: money },
      tds: { type: Number, default: 0, set: money },
      recoveries: { type: Number, default: 0, set: money },
      other: { type: Number, default: 0, set: money },
      total: { type: Number, default: 0, set: money },
    },

    netPayable: { type: Number, default: 0, set: money },

    status: {
      type: String,
      enum: ["generated", "approved", "paid", "on_hold"],
      default: "generated",
    },

    autoGenerated: { type: Boolean, default: false }, // true = created by the notice-period auto-exit cron

    remarks: { type: String, trim: true, maxlength: 500, default: "" },

    generatedBy: { type: mongoose.Schema.Types.ObjectId, default: null },
    generatedByModel: { type: String, enum: ["Admin", "SuperAdmin", null], default: null },
    approvedBy: { type: mongoose.Schema.Types.ObjectId, default: null },
    approvedByModel: { type: String, enum: ["Admin", "SuperAdmin", null], default: null },
    paidOn: { type: Date, default: null },
  },
  { timestamps: true }
);

fnfSchema.index({ employee: 1 }, { unique: true });
fnfSchema.index({ organisation_id: 1, status: 1 });

module.exports = mongoose.models.FnF || mongoose.model("FnF", fnfSchema);