// Editable while still "generated" — corrections before approval/payment.
const updateFnF = async (req, res) => {
  const organisation_id = req.admin.organisation_id;
  const { id } = req.params;
  const {
    leaveEncashment, gratuity, bonus, otherEarnings, otherIncomeItems,
    salaryOnHold, reimbursementOnHold, assetRecovery,
    pf, professionalTax, tds, deductions: recoveriesInput, otherDeductions,
    pan, bankAccountNumber, bankName,
    remarks, dateOfLeaving,
  } = req.body;

  const fnf = await FnF.findOne({ _id: id, organisation_id });
  if (!fnf) return res.status(404).json({ success: false, message: "FnF record not found" });
  if (fnf.status !== "generated")
    return res.status(400).json({ success: false, message: "Only a record still in 'generated' status can be edited" });

  if (otherIncomeItems !== undefined) {
    const items = otherIncomeItems || [];
    fnf.otherIncome = { items, total: items.reduce((s, i) => s + (Number(i.amount) || 0), 0) };
  } else if ([leaveEncashment, gratuity, bonus, otherEarnings].some((v) => v !== undefined)) {
    const existing = fnf.otherIncome?.items || [];
    const items = buildOtherIncomeItems({
      leaveEncashment: leaveEncashment !== undefined ? leaveEncashment : namedAmountFrom(existing, "Leave Encashment"),
      gratuity: gratuity !== undefined ? gratuity : namedAmountFrom(existing, "Gratuity"),
      bonus: bonus !== undefined ? bonus : namedAmountFrom(existing, "Bonus"),
      otherEarnings: otherEarnings !== undefined ? otherEarnings : namedAmountFrom(existing, "Other Earnings"),
    });
    fnf.otherIncome = { items, total: items.reduce((s, i) => s + i.amount, 0) };
  }

  const holding = { ...fnf.holding.toObject() };
  if (salaryOnHold !== undefined) holding.salaryOnHold = Number(salaryOnHold) || 0;
  if (reimbursementOnHold !== undefined) holding.reimbursementOnHold = Number(reimbursementOnHold) || 0;
  if (assetRecovery !== undefined) holding.assetRecovery = Number(assetRecovery) || 0;
  holding.total = holding.salaryOnHold + holding.reimbursementOnHold + holding.assetRecovery;
  fnf.holding = holding;

  const deductions = { ...fnf.deductions.toObject() };
  if (pf !== undefined) deductions.pf = Number(pf) || 0;
  if (professionalTax !== undefined) deductions.professionalTax = Number(professionalTax) || 0;
  if (tds !== undefined) deductions.tds = Number(tds) || 0;
  if (recoveriesInput !== undefined) deductions.recoveries = Number(recoveriesInput) || 0;
  if (otherDeductions !== undefined) deductions.other = Number(otherDeductions) || 0;
  deductions.total = deductions.pf + deductions.professionalTax + deductions.tds + (deductions.recoveries || 0) + deductions.other;
  fnf.deductions = deductions;

  if (pan !== undefined || bankAccountNumber !== undefined || bankName !== undefined) {
    const snapshot = { ...fnf.employeeSnapshot.toObject() };
    if (pan !== undefined) snapshot.pan = pan;
    if (bankAccountNumber !== undefined) snapshot.bankAccountNumber = bankAccountNumber;
    if (bankName !== undefined) snapshot.bankName = bankName;
    fnf.employeeSnapshot = snapshot;
  }

  fnf.netPayable = fnf.income.total + fnf.otherIncome.total - fnf.holding.total - fnf.deductions.total;

  if (remarks !== undefined) fnf.remarks = remarks;
  if (dateOfLeaving !== undefined) fnf.dateOfLeaving = dateOfLeaving ? new Date(dateOfLeaving) : null;
  await fnf.save();

  res.status(200).json({ success: true, fnf });
};

const updateFnFStatus = async (req, res) => {
  const organisation_id = req.admin.organisation_id;
  const { id } = req.params;
  const { status } = req.body;

  if (!["approved", "paid", "on_hold"].includes(status))
    return res.status(400).json({ success: false, message: "status must be approved, paid or on_hold" });

  const setFields = { status };
  if (status === "approved") {
    setFields.approvedBy = req.admin._id;
    setFields.approvedByModel = req.actorModel || "Admin";
  }
  if (status === "paid") setFields.paidOn = new Date();

  const fnf = await FnF.findOneAndUpdate({ _id: id, organisation_id }, { $set: setFields }, { new: true });
  if (!fnf) return res.status(404).json({ success: false, message: "FnF record not found" });

  res.status(200).json({ success: true, fnf });
};

const deleteFnF = async (req, res) => {
  const organisation_id = req.admin.organisation_id;
  const { id } = req.params;

  const fnf = await FnF.findOne({ _id: id, organisation_id });
  if (!fnf) return res.status(404).json({ success: false, message: "FnF record not found" });
  if (fnf.status !== "generated")
    return res.status(400).json({ success: false, message: "Only a record still in 'generated' status can be deleted" });

  await FnF.deleteOne({ _id: id, organisation_id });
  res.status(200).json({ success: true, message: "FnF record deleted" });
};

